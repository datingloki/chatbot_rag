"""Поисковый запрос из сообщений пользователя.

Пользователи пишут разговорно («как поставить на комп»), а в документации — «установка»,
«компьютер». Ни BM25, ни небольшая эмбеддинг-модель эти пары не сводят, поэтому перед
поиском разговорные слова заменяются на слова документации. Подтверждения из ответа на
уточнение домена («да, касается») смысла не несут и из запроса убираются.

Текст для LLM не меняется: модель видит сообщения пользователя как есть.
"""
from __future__ import annotations

import re

SYNONYMS = {
    "поставить": "установить", "поставлю": "установлю", "поставила": "установила", "поставил": "установил",
    "ставить": "устанавливать", "ставится": "устанавливается", "ставлю": "устанавливаю",
    "комп": "компьютер", "компа": "компьютера", "компе": "компьютере", "компу": "компьютеру",
    "пк": "компьютер", "ноут": "ноутбук",
    "прога": "программа", "прогу": "программу", "проги": "программы", "проге": "программе",
    "винда": "windows", "винду": "windows", "винде": "windows",
}
WORD_RE = re.compile(r"[а-яёa-z]+", re.I)
PRODUCT_REF_RE = re.compile(
    r"\bваш(?:а|у|ей|ем|его)?\s+(программ\w*|продукт\w*|конфигурац\w*)", re.I)
AFFIRM_RE = re.compile(r"\b(?:да|ага|угу|конечно|верно|именно|точно|касается|относится)\b[,.!]*\s*", re.I)


def normalize(text: str) -> str:
    text = PRODUCT_REF_RE.sub(lambda m: f"{m.group(1)} 1С:Полиграфия", text)

    def repl(m: re.Match) -> str:
        w = m.group(0)
        new = SYNONYMS.get(w.lower())
        return new if new is not None else w

    return WORD_RE.sub(repl, text)


def build_query(messages: list[str]) -> str:
    """Первое сообщение — исходный вопрос; в ответах на уточнения убираются подтверждения
    («Да, касается. Как …» → «Как …», «да, в заказе» → «в заказе»)."""
    parts = []
    for i, m in enumerate(messages):
        if i > 0:
            m = AFFIRM_RE.sub("", m).strip()
        m = normalize(m)
        if m:
            parts.append(m)
    return "\n".join(parts)

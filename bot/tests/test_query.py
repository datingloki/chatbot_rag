"""Поисковый запрос: разговорные слова → слова документации, подтверждения убираются."""
from polybot.retrieval.query import build_query, normalize


def test_colloquial_words_normalized():
    assert normalize("Как поставить прогу на комп?") == "Как установить программу на компьютер?"
    assert normalize("Где скачать вашу программу?") == "Где скачать программу 1С:Полиграфия?"
    assert normalize("Поставьте галочку") == "Поставьте галочку"        # другие формы не трогаем


def test_affirmations_removed_from_follow_ups_only():
    assert build_query(["Да, как это сделать?"]) == "Да, как это сделать?"
    assert build_query(["Как поставить на комп?", "Да, касается. Как поставить вашу программу?"]) == (
        "Как установить на компьютер?\nКак установить программу 1С:Полиграфия?")
    assert build_query(["не считается бумага", "да"]) == "не считается бумага"
